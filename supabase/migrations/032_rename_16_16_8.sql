-- 032_rename_16_16_8.sql
-- เปลี่ยนชื่อสูตร 16-16-8 จาก "ปุ๋ยอ้อย" เป็น "ปุ๋ยเคมี 16-16-8"
--
-- เหตุผล: ในตาราง crop_fertilizer_plan ของกรมฯ เกรดนี้ถูกใช้กับข้าวโพดฝักสด
-- ข้าวโพดเลี้ยงสัตว์ และมันสำปะหลังด้วย ไม่ได้ใช้แค่อ้อย
-- ชื่อเดิมทำให้คนปลูกพืชอื่นเข้าใจว่าไม่ใช่ปุ๋ยของตัวเอง
-- และยังตั้งชื่อคนละแบบกับปุ๋ยเชิงประกอบตัวอื่นในตารางที่ใช้รูปแบบ "ปุ๋ยเคมี <เกรด>"
--
-- ปลอดภัย: ระบบอ้างถึงสูตรปุ๋ยด้วย id (analyses.blend_formula_ids) ไม่ใช่ชื่อ
-- และไม่มีโค้ดตรงไหน hard-code ชื่อนี้ไว้ (ตรวจด้วย grep ทั้ง src/ แล้ว)
-- ผลกระทบเดียวคือไฟล์นำเข้า Excel/CSV เก่าที่พิมพ์ว่า "ปุ๋ยอ้อย" ในช่องปุ๋ย
-- จะจับคู่ไม่ได้ ให้ใช้เกรด "16-16-8" แทน ซึ่งจับคู่ได้ทั้งก่อนและหลังเปลี่ยนชื่อ

update public.fertilizer_formulas
   set name = 'ปุ๋ยเคมี 16-16-8'
 where grade = '16-16-8'
   and name = 'ปุ๋ยอ้อย';

