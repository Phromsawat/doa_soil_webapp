-- เพิ่มสูตรปุ๋ยที่ขายจริงในท้องตลาด แต่ระบบยังไม่รู้จัก
--
-- ที่มา: เทียบรายการสินค้าของผู้ผลิตปุ๋ยเคมีรายใหญ่ (puimongkut.com/th/site/product
--        ตรวจเมื่อ 3 ก.ย. 2569) กับตาราง fertilizer_formulas ที่มีอยู่
--        จาก 15 รายการในแคตตาล็อก มี 8 สูตรที่ระบบมีแล้ว (46-0-0, 21-0-0, 18-46-0,
--        0-0-60, 15-15-15, 13-13-21, 15-7-18, 20-8-20) เหลือ 3 สูตรตามด้านล่าง
--
-- เก็บเฉพาะตัวเลข N-P2O5-K2O ซึ่งเป็นนิยามของสูตรเอง ไม่ผูกกับยี่ห้อใด
-- สินค้าจริงมักพ่วง MgO/S/B มาด้วย แต่ตารางนี้ยังไม่มีช่องเก็บธาตุรอง จึงไม่บันทึก
--
-- ที่ไม่ใส่: หินฟอสเฟต / โบแรกซ์ / คีเซอร์ไรต์ — เป็นธาตุรองหรือมี P ละลายได้แค่ 3%
--   blendFertilizer() กรองสูตรที่ N/P/K เป็น 0 ทั้งหมดทิ้งอยู่แล้ว (ตัวแปร usable)
--   ใส่เข้ามาก็จะโผล่ในรายการให้เลือกแต่คำนวณไม่ออก กลายเป็นทางตันของผู้ใช้
--
-- ตารางนี้ไม่มี unique key บน grade -> on conflict ใช้ไม่ได้
-- จึงกันเพิ่มซ้ำด้วย where not exists เพื่อให้รันกี่รอบก็ได้ผลเท่าเดิม

insert into public.fertilizer_formulas
  (name, grade, n_percent, p2o5_percent, k2o_percent, kind, sort_order, notes)
select v.name, v.grade, v.n, v.p, v.k, 'chemical', v.sort_order, v.notes
from (values
  -- ไนโตรเจนสูง จัดไว้ถัดจากยูเรีย (46-0-0 อยู่ที่ sort_order 10)
  ('ปุ๋ยเคมี 40-0-0', '40-0-0', 40, 0,  0, 15,
   'ไนโตรเจนสูง ใช้เร่งการเจริญเติบโต สินค้าในตลาดมักพ่วงแมกนีเซียมและกำมะถันมาด้วย'),
  -- ปุ๋ยผสมปั้นเม็ด ต่อท้ายกลุ่มปุ๋ยเชิงประกอบ (110-180)
  ('ปุ๋ยเคมี 18-8-8',  '18-8-8',  18, 8,  8, 190,
   'ปุ๋ยผสมบำรุงต้น ใช้ได้กว้างทั้งข้าว พืชไร่ และไม้ผล'),
  ('ปุ๋ยเคมี 14-7-35', '14-7-35', 14, 7, 35, 200,
   'โพแทสเซียมสูง ใช้ช่วงติดผลถึงเก็บเกี่ยว เพื่อเพิ่มคุณภาพผลผลิต')
) as v(name, grade, n, p, k, sort_order, notes)
where not exists (
  select 1 from public.fertilizer_formulas f where f.grade = v.grade
);

