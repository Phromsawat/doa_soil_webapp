-- 016_crop_stage_split.sql
-- "สัดส่วนการแบ่งใส่ปุ๋ยตามระยะ" สำหรับโหมดปุ๋ยผสม 100% (compound) ของไม้ผล
-- ที่มา: ไฟล์ "1.ขัอมูลคำแนะนำการให้ปุ๋ยตามค่าวิเคราะห์ดิน.xlsx" ชีต "ฐานระยะแบ่งการให้ปุ๋ย"
--
-- ต่างจาก crop_fertilizer_plan (ตารางปริมาณตายตัว): ตารางนี้เก็บ "สัดส่วน" ต่อระยะ
-- แล้วให้แอปเอาผล blend (ปุ๋ยที่ผู้ใช้เลือก) มาคูณสัดส่วน -> ปริมาณต่อระยะ
-- แต่ละสูตรใช้สัดส่วนของธาตุที่มันเป็นแหล่งหลัก (ปุ๋ย N ใช้ n_frac, ปุ๋ย P ใช้ p_frac, ปุ๋ย K ใช้ k_frac)
--
-- หมายเหตุควิร์กต้นทาง: มะพร้าว (รวม N/P=0.67, K=1.2) และ สับปะรด (รวม P=0.5)
--   ยอดสัดส่วนไม่ครบ 1.0 ตามไฟล์ต้นฉบับกรมฯ — เก็บตามต้นทางเพื่อให้ผลตรงกับเครื่องคิดเลขของกรมฯ

create table if not exists public.crop_stage_split (
  id uuid primary key default gen_random_uuid(),
  crop_id uuid not null references public.crops(id) on delete cascade,
  stage_order int not null,
  stage_name text not null,      -- เช่น "ระยะบำรุงต้น", "ครั้งที่ 1"
  stage_desc text,               -- เช่น "(ก่อนออกดอก 1-2 เดือน)"
  unit text,                     -- หน่วยอ้างอิงจากต้นทาง (กรัม/ต้น | กก./ไร่)
  n_frac numeric not null default 0,   -- สัดส่วนปุ๋ยไนโตรเจนที่ใส่ในระยะนี้
  p_frac numeric not null default 0,   -- สัดส่วนปุ๋ยฟอสฟอรัส
  k_frac numeric not null default 0,   -- สัดส่วนปุ๋ยโพแทสเซียม
  created_at timestamptz not null default now(),
  unique (crop_id, stage_order)
);

create index if not exists crop_stage_split_crop_idx on public.crop_stage_split (crop_id, stage_order);

