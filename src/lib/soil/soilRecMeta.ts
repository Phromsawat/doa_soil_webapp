// ตัวเลขในตารางดึงจาก DB (fertilizer_recommendations) ซึ่งเป็นตัวเดียวกับที่ใช้คำนวณ
// ไฟล์นี้เก็บเฉพาะสิ่งที่ DB ไม่มี:
//   - basis    : ฐานของอัตราแนะนำ ซึ่งต้นฉบับเขียนไว้ในหัวคอลัมน์ เช่น "(ขนาดทรงพุ่ม 8 เมตร)"
//   - decimals : จำนวนทศนิยมที่ต้นฉบับพิมพ์ช่วงค่าวิเคราะห์ไว้ (DB เก็บเป็นตัวเลขล้วน
//                จึงกู้กลับเองไม่ได้) ใส่เฉพาะพืชที่ต้นฉบับพิมพ์ศูนย์ท้ายเกินกว่าที่เลขจะบอกได้
// พืชที่ไม่มีในนี้ = ไม่ต้องมีข้อมูลเพิ่ม

import type { RecNutrient } from "@/lib/supabase/soilRecommendation"

export interface SoilRecMeta {
  /** ฐานของอัตราแนะนำ เช่น "ขนาดทรงพุ่ม 8 เมตร" */
  basis?: string
  /** จำนวนทศนิยมขั้นต่ำของช่วงค่าวิเคราะห์ แยกตามธาตุ */
  decimals?: Partial<Record<RecNutrient, number>>
}

export const SOIL_REC_META: Record<string, SoilRecMeta> = {
  // ไม้ผล — ต้นฉบับระบุขนาดทรงพุ่มที่ใช้อ้างอิงอัตรา
  ทุเรียน: { basis: "ขนาดทรงพุ่ม 8 เมตร" },
  มังคุด: { basis: "ขนาดทรงพุ่ม 6-8 เมตร" },
  เงาะ: { basis: "ขนาดทรงพุ่ม 6-8 เมตร" },
  มะม่วง: { basis: "ขนาดทรงพุ่ม 5 เมตร" },
  ลำไย: { basis: "ขนาดทรงพุ่ม 8 เมตร" },
  ลิ้นจี่: { basis: "ขนาดทรงพุ่ม 6 เมตร" },
  ส้ม: { basis: "ขนาดทรงพุ่ม 4 เมตร" },
  มะพร้าว: { basis: "ขนาดทรงพุ่ม 5 เมตร" },

  // ต้นฉบับพิมพ์ช่วง OM เป็น < 0.60 / 0.60-1.00 / 1.00-2.00 / >2.00
  มันสำปะหลัง: { decimals: { om: 2 } },
}

export function getSoilRecMeta(cropName: string): SoilRecMeta {
  return SOIL_REC_META[cropName] ?? {}
}
